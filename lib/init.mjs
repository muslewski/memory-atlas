import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadConfig, PROFILES } from './config.mjs'
import { findRepoRoot, findVaultDir } from './detect.mjs'
import { defaultState, STATE_FILE } from './state.mjs'

const PACKAGE_ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const TEMPLATES_DIR = path.join(PACKAGE_ROOT, 'templates')

const NOTE_TEMPLATE_NAMES = [
  'zone.md',
  'flow.md',
  'decision.md',
  'spec.md',
  'plan.md',
  'program.md',
  'idea.md',
  'debt.md',
  'pillar.md',
  'report.md',
]

/**
 * SPEC.md §2 core skeleton, resolved through `config.folders` so a
 * remapped vault (e.g. `"ideas": "notes/sparks"`) scaffolds at the mapped
 * location instead of the default one.
 *
 * @param {Record<string, string>} folders
 * @returns {string[]}
 */
function coreDirs(folders) {
  return [
    folders.zones,
    folders.decisions,
    folders.specs,
    folders.plans,
    folders.ideas,
    folders.techDebt,
    folders.templates,
  ]
}

